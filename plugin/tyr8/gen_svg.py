#!/usr/bin/env python3
"""Writes tyr8.svg (the screen artwork) and tyr8_geom.h (the same geometry for tyr8.c).

The OP-1's native SVG renderer takes a small subset: groups, lines, circles, polylines, M/L/C/Z paths, at most four
decimals, no CSS, no opacity, and it is not known to combine nested transforms. So the moving parts are sibling
groups, each given a complete matrix by tyr8.c every frame:
  #ground-line          static baseline (bump ticks are drawn by code)
  #wheel-rig            far side of the tyre, then the near face (filled black, so it hides what is behind it), rim
                        and hub rings: squash + scale + translate (size, bounce)
  #wheel-spin           spokes, lug nuts, valve: rotate, then as the rig
  #tread0 .. #tread13   the near face of one tread block each: as wheel-spin, plus a radial squash (slick .. lug)
Three-quarter view, as an oblique projection so that every part stays one affine matrix: the wheel's face is drawn
round here and squashed sideways by KX in code; the tyre's width is the offset (WX, WY) on screen, to the far side.
The rings are cubic paths, not <circle>: a path is transformed point by point, a circle may not be squashed natively.
The far faces of the tread blocks and the edges across the tread are drawn by tyr8.c (only on the side that shows).
Copyright (C) 2026 David Hanover. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
"""
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
W, H = 320, 160
GROUND_Y = 140          # 12 px above the handoff's 148: the native panel wants clearance at the lower edge
HUB_X, HUB_Y = 172, 78  # hub centre of the near face of the full-size wheel as drawn
R_TYRE = 50             # carcass radius, where the tread blocks sit
R_INNER = 45
R_RIM = 30
R_DISH = 23             # the back of the rim's dish, seen through the spokes
R_HUB = 6
TREAD_N = 14
TREAD_H = 10            # full lug height
TREAD_W = 6             # half width at the carcass
TREAD_WT = 4.5          # half width at the top
KX = 0.8                # sideways squash of the face: the wheel is turned 37 degrees away
WX, WY = -22, -7        # the tyre's width on screen (full size), from the near face to the far one
WHITE, GREY, BLUE, RED, BLACK = '#FFFFFF', '#6F7173', '#4D9EFF', '#FF3A5D', '#000000'
K = 0.5523              # cubic circle


def f(v):
    s = f'{v:.2f}'.rstrip('0').rstrip('.')
    return '0' if s == '-0' else s


def polar(r, a, tang=0.0):
    """point at radius r, angle a (radians, clockwise on screen), shifted tang px along the tangent"""
    return (HUB_X + r * math.cos(a) - tang * math.sin(a), HUB_Y + r * math.sin(a) + tang * math.cos(a))


def line(p, q, col, w):
    return (f'<line fill="none" stroke="{col}" stroke-width="{w}" stroke-linecap="round" '
            f'x1="{f(p[0])}" y1="{f(p[1])}" x2="{f(q[0])}" y2="{f(q[1])}"/>')


def ring(r, col, w, c=(HUB_X, HUB_Y), fill='none'):
    """a circle as four cubics, one closed contour"""
    x, y, k = c[0], c[1], r * K
    d = (f'M{f(x + r)},{f(y)}C{f(x + r)},{f(y + k)} {f(x + k)},{f(y + r)} {f(x)},{f(y + r)}'
         f'C{f(x - k)},{f(y + r)} {f(x - r)},{f(y + k)} {f(x - r)},{f(y)}'
         f'C{f(x - r)},{f(y - k)} {f(x - k)},{f(y - r)} {f(x)},{f(y - r)}'
         f'C{f(x + k)},{f(y - r)} {f(x + r)},{f(y - k)} {f(x + r)},{f(y)}Z')
    return f'<path fill="{fill}" stroke="{col}" stroke-width="{w}" d="{d}"/>'


def back(t):
    """the hub centre t of the tyre's width back, in the drawing (before the squash)"""
    return (HUB_X + t * WX / KX, HUB_Y + t * WY)


out = ['<?xml version="1.0" encoding="utf-8"?>',
       f'<svg version="1.1" xmlns="http://www.w3.org/2000/svg" width="{W}px" height="{H}px" viewBox="0 0 {W} {H}">',
       '<!-- generated by gen_svg.py: tyr8, a rolling tyre in three-quarter view. Motion, tread height, the far tread '
       'faces, ground bumps and gauges by tyr8.c -->',
       '<g id="ground-line">', line((4, GROUND_Y), (316, GROUND_Y), GREY, 1.5), '</g>',
       '<g id="wheel-rig">',
       ring(R_TYRE, WHITE, 1.5, back(1)),                      # far edge of the tread
       ring(R_TYRE, WHITE, 2, fill=BLACK),                     # near face: hides the far edge behind it
       ring(R_INNER, GREY, 1), ring(R_RIM, WHITE, 1.5),
       ring(R_DISH, GREY, 1, back(0.3)),
       ring(R_HUB, WHITE, 1.5), '</g>',
       '<g id="wheel-spin">']
for i in range(5):
    a = 2 * math.pi * i / 5 - math.pi / 2
    out.append(line(polar(R_HUB + 2, a), polar(R_RIM - 2, a), WHITE, 1.5))
    b = a + math.pi / 5
    out.append(ring(1.5, BLUE, 1, polar(13, b)))
out.append(line(polar(R_RIM + 3, 0.5), polar(R_RIM + 8, 0.5), RED, 1.5))          # valve stem: shows the spin
out.append('</g>')
for i in range(TREAD_N):
    a = 2 * math.pi * i / TREAD_N
    pts = [polar(R_TYRE, a, -TREAD_W), polar(R_TYRE + TREAD_H, a, -TREAD_WT),
           polar(R_TYRE + TREAD_H, a, TREAD_WT), polar(R_TYRE, a, TREAD_W)]
    out.append(f'<g id="tread{i}"><polyline fill="none" stroke="{WHITE}" stroke-width="1.5" stroke-linejoin="round" '
               f'points="{" ".join(f"{f(x)},{f(y)}" for x, y in pts)}"/></g>')
out.append('</svg>')
(HERE / 'tyr8.svg').write_text('\n'.join(out) + '\n')

(HERE / 'tyr8_geom.h').write_text(f'''/* generated by gen_svg.py: the geometry of tyr8.svg (screen units, 320 x 160) */
#ifndef TYR8_GEOM_H
#define TYR8_GEOM_H
#define TY_GROUND_Y {GROUND_Y}
#define TY_HUB_X    {HUB_X}
#define TY_HUB_Y    {HUB_Y}
#define TY_R_TYRE   {R_TYRE}
#define TY_TREAD_N  {TREAD_N}
#define TY_TREAD_H  {TREAD_H}
#define TY_TREAD_W  {int(TREAD_W * 1024)}      /* half width at the carcass, Q10 */
#define TY_TREAD_WT {int(TREAD_WT * 1024)}     /* half width at the top, Q10 */
#define TY_KX       {int(KX * 1024 + 0.5)}       /* sideways squash of the wheel's face, Q10 */
#define TY_WX       ({WX})                     /* the tyre's width on screen at full size, px */
#define TY_WY       ({WY})
#endif
''')
print('tyr8.svg', (HERE / 'tyr8.svg').stat().st_size, 'bytes')
